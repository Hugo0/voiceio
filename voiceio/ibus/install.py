"""Installing voiceio into IBus: the engine launcher, the component XML, the
environment IBus needs, and the GNOME input source.

Everything here writes files or restarts IBus, so it runs from setup, doctor
and daemon start — never from the health loop. The typer only probes.
"""
from __future__ import annotations

import logging
import os
import shutil
import stat
import subprocess
import sys
from pathlib import Path

log = logging.getLogger(__name__)

COMPONENT_DIR = Path.home() / ".local" / "share" / "ibus" / "component"
COMPONENT_DEST = COMPONENT_DIR / "voiceio.xml"
LAUNCHER_DIR = Path.home() / ".local" / "share" / "voiceio"
LAUNCHER_PATH = LAUNCHER_DIR / "voiceio-ibus-engine"


_IBUS_GI_PROBE = "import gi; gi.require_version('IBus', '1.0')"


def system_python() -> str | None:
    """An interpreter with IBus GObject bindings (distro packages, not pip)."""
    from voiceio.platform import find_system_python
    return find_system_python(_IBUS_GI_PROBE)


def gnome_source_configured() -> bool:
    """Check if voiceio is in GNOME input sources."""
    from voiceio.platform import detect
    if not detect().is_gnome:
        return True  # non-GNOME: no input source needed
    try:
        result = subprocess.run(
            ["gsettings", "get", "org.gnome.desktop.input-sources", "sources"],
            capture_output=True, text=True, timeout=3,
        )
        return result.returncode == 0 and "('ibus', 'voiceio')" in result.stdout
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return True  # can't check, assume OK


def has_ibus_gi() -> bool:
    return system_python() is not None


def daemon_running() -> bool:
    """Check if the IBus daemon (ibus-daemon) is running."""
    try:
        result = subprocess.run(
            ["ibus", "address"], capture_output=True, text=True, timeout=3,
        )
        return result.returncode == 0 and bool(result.stdout.strip())
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return False


def component_installed() -> bool:
    """True if the component XML and launcher exist *and are current*.

    Content, not existence: the launcher bakes in interpreter paths, which go
    stale when a venv moves or a Nix store path is garbage-collected.
    """
    try:
        return (COMPONENT_DEST.read_text() == _component_xml()
                and LAUNCHER_PATH.read_text() == _launcher_script())
    except OSError:
        return False


def refresh_stale_launcher() -> bool:
    """Rewrite the launcher when only its baked-in paths went stale.

    An upgrade into a new venv leaves the old interpreter paths in the
    launcher, so the probe reports the component missing and the daemon falls
    back to keystrokes. The component XML is unchanged in that case, so this
    needs no IBus restart (unlike install_component) and is safe at start-up.
    """
    try:
        if COMPONENT_DEST.read_text() != _component_xml():
            return False
        if LAUNCHER_PATH.read_text() == _launcher_script():
            return False
    except OSError:
        return False
    _write_launcher()
    log.info("Refreshed stale IBus launcher at %s", LAUNCHER_PATH)
    return True


def _write_launcher() -> None:
    LAUNCHER_DIR.mkdir(parents=True, exist_ok=True)
    LAUNCHER_PATH.write_text(_launcher_script())
    LAUNCHER_PATH.chmod(LAUNCHER_PATH.stat().st_mode | stat.S_IEXEC | stat.S_IXGRP | stat.S_IXOTH)


def _get_pkg_root() -> str:
    """Get the directory that contains the ``voiceio`` package.

    For a normal pip/pipx install this is the site-packages directory.
    For an editable (``pip install -e .``) or bare git-clone this is the
    project source root.  Either way, adding the returned path to
    PYTHONPATH lets ``python -m voiceio.ibus.engine`` work.
    """
    # Path(__file__) -> .../voiceio/typers/ibus.py
    # .parent        -> .../voiceio/typers/
    # .parent        -> .../voiceio/           (the package dir)
    # .parent        -> .../                   (site-packages or source root)
    return str(Path(__file__).resolve().parent.parent.parent)


def _launcher_script() -> str:
    """The IBus engine launcher: system Python (has gi) with voiceio on PYTHONPATH."""
    pkg_root = _get_pkg_root()
    # The Python running *now* has voiceio installed; it is the fallback when
    # the system Python cannot import voiceio.
    installing_python = sys.executable or "python3"
    system_py = system_python() or installing_python
    return f"""#!/bin/bash
# Generated by voiceio. Do not edit manually.
# voiceio package root baked in at install time:
VOICEIO_PKG_ROOT="{pkg_root}"

# Prefer the system Python (has GObject / IBus bindings).
SYSTEM_PY="{system_py}"
# The Python that installed voiceio (fallback).
INSTALL_PY="{installing_python}"

# Add voiceio's package root so the system Python can import it.
export PYTHONPATH="${{VOICEIO_PKG_ROOT}}:${{PYTHONPATH}}"

# Try system Python first (needed for gi / IBus bindings).
if "$SYSTEM_PY" -c "import voiceio" 2>/dev/null; then
    exec "$SYSTEM_PY" -m voiceio.ibus.engine "$@"
fi

# Fallback: the Python that installed voiceio (may be a venv/pipx Python
# that already has gi accessible via system site-packages).
exec "$INSTALL_PY" -m voiceio.ibus.engine "$@"
"""


def _component_xml() -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<component>
    <name>org.voiceio.ibus</name>
    <description>VoiceIO voice input</description>
    <exec>{LAUNCHER_PATH}</exec>
    <version>1.0</version>
    <author>voiceio</author>
    <license>MIT</license>
    <textdomain>voiceio</textdomain>
    <engines>
        <engine>
            <name>voiceio</name>
            <language>other</language>
            <license>MIT</license>
            <author>voiceio</author>
            <layout>us</layout>
            <longname>VoiceIO</longname>
            <description>Voice-to-text input</description>
            <rank>0</rank>
        </engine>
    </engines>
</component>
"""


def install_component() -> bool:
    """Install the IBus engine launcher and component XML.

    Writes a launcher script (with PYTHONPATH baked in) and a component XML
    that points to it, then refreshes the IBus cache and restarts IBus.

    Returns True if installed successfully.
    """
    _write_launcher()
    log.info("Installed IBus engine launcher to %s", LAUNCHER_PATH)

    COMPONENT_DIR.mkdir(parents=True, exist_ok=True)
    COMPONENT_DEST.write_text(_component_xml())
    log.info("Installed IBus component to %s", COMPONENT_DEST)

    # IBus needs IBUS_COMPONENT_PATH to scan ~/.local/share/ibus/component/
    env = ibus_env()

    # Refresh IBus cache and restart so it discovers the new engine
    try:
        subprocess.run(
            ["ibus", "write-cache"], capture_output=True, timeout=5, env=env,
        )
    except (FileNotFoundError, subprocess.TimeoutExpired):
        pass

    try:
        subprocess.run(
            ["ibus", "restart"], capture_output=True, timeout=5, env=env,
        )
        log.info("IBus restarted with IBUS_COMPONENT_PATH")
    except (FileNotFoundError, subprocess.TimeoutExpired):
        log.warning("Could not restart IBus. Restart manually: ibus restart")

    # Persist IBUS_COMPONENT_PATH so it survives reboot
    persist_ibus_env()

    return True


def _ibus_component_path() -> str:
    """IBUS_COMPONENT_PATH with the user dir prepended to the system dirs.

    Setting the variable *replaces* ibus-daemon's compiled-in search path, so
    the system dirs must be rediscovered or every other engine vanishes. A
    hardcoded /usr/share misses NixOS (/run/current-system/sw/share) and
    /usr/local installs. Derive from the ibus binary's prefix (unresolved, so
    Nix profile symlinks stay stable across upgrades) and XDG_DATA_DIRS.
    """
    dirs = [str(COMPONENT_DIR)]
    ibus_bin = shutil.which("ibus")
    if ibus_bin:
        dirs.append(str(Path(ibus_bin).parent.parent / "share" / "ibus" / "component"))
    data_dirs = os.environ.get("XDG_DATA_DIRS") or "/usr/local/share:/usr/share"
    dirs += [f"{d.rstrip('/')}/ibus/component" for d in data_dirs.split(":") if d]
    dirs.append("/usr/share/ibus/component")
    return ":".join(dict.fromkeys(dirs))


def ibus_env() -> dict[str, str]:
    """Build environment with IBUS_COMPONENT_PATH including user component dir."""
    env = os.environ.copy()
    env["IBUS_COMPONENT_PATH"] = _ibus_component_path()
    return env


def persist_ibus_env() -> None:
    """Write IBUS_COMPONENT_PATH to environment.d so it survives reboot.

    See systemd environment.d(5). Files in ~/.config/environment.d/ are
    loaded by systemd user services and login sessions.
    """
    env_dir = Path.home() / ".config" / "environment.d"
    env_file = env_dir / "voiceio.conf"
    content = f"IBUS_COMPONENT_PATH={_ibus_component_path()}\n"

    try:
        if env_file.exists() and env_file.read_text() == content:
            return  # already persisted
        env_dir.mkdir(parents=True, exist_ok=True)
        env_file.write_text(content)
        log.info("Persisted IBUS_COMPONENT_PATH to %s", env_file)
    except OSError as e:
        log.debug("Could not persist IBUS_COMPONENT_PATH: %s", e)


def ensure_gnome_input_source() -> None:
    """Add ('ibus', 'voiceio') to GNOME input sources if running GNOME."""
    from voiceio.platform import detect
    if not detect().is_gnome:
        return

    try:
        result = subprocess.run(
            ["gsettings", "get", "org.gnome.desktop.input-sources", "sources"],
            capture_output=True, text=True, timeout=3,
        )
        if result.returncode != 0:
            return
        current = result.stdout.strip()
        if "('ibus', 'voiceio')" in current:
            log.debug("VoiceIO already in GNOME input sources")
            return

        # Parse current sources and append voiceio
        # Format: [('xkb', 'us'), ('xkb', 'fr')]
        if current.startswith("@as"):
            # Empty array
            new_sources = "[('ibus', 'voiceio')]"
        elif current == "[]":
            new_sources = "[('ibus', 'voiceio')]"
        else:
            # Insert voiceio at the end (keep current keyboard as default)
            new_sources = current.rstrip("]") + ", ('ibus', 'voiceio')]"

        subprocess.run(
            ["gsettings", "set", "org.gnome.desktop.input-sources", "sources", new_sources],
            capture_output=True, text=True, timeout=3,
        )
        log.info("Added VoiceIO to GNOME input sources: %s", new_sources)
    except (FileNotFoundError, subprocess.TimeoutExpired):
        pass


def ensure() -> bool:
    """Install the component and add the GNOME input source, as needed.
    True when the component is in place."""
    installed = component_installed() or install_component()
    if installed:
        ensure_gnome_input_source()
    return installed
